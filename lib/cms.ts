export function slugify(input: string): string {
  const normalized = (input || "")
    .normalize("NFKD")
    .replace(/\p{Diacritic}+/gu, "")
    .toLowerCase()
    .trim();

  const ascii = normalized
    .replace(/[^\p{L}\p{N}\s-]+/gu, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 200);

  if (ascii) return ascii;
  return `untitled-${Math.random().toString(36).slice(2, 8)}`;
}
